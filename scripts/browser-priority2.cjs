const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('node:fs');
const {spawn}=require('node:child_process');
let server,browser;
(async()=>{
 server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5188','--strictPort'],{windowsHide:true,stdio:['ignore','pipe','pipe']});
 await new Promise((resolve,reject)=>{server.stdout.on('data',chunk=>{if(chunk.toString().includes('Local:'))resolve();});server.on('error',reject);server.on('exit',code=>reject(Error('Server exit '+code)));});
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
 await page.goto('http://127.0.0.1:5188/',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
 await page.locator('#nta-composite').scrollIntoViewIfNeeded();
 await page.locator('#composite-map path').first().waitFor();
 const result={paths:await page.locator('#composite-map path').count(),status:await page.locator('#composite-status').innerText()};
 if(result.paths!==197)throw Error('Missing NTA paths');
 const before=await page.locator('#composite-map').innerHTML();
 await page.locator('[data-composite-weight="transit"]').fill('10');
 const after=await page.locator('#composite-map').innerHTML();if(before===after)throw Error('Map did not react to weight');
 await page.locator('#composite-reset').click();
 fs.mkdirSync('qa-priority2',{recursive:true});
 await page.locator('#nta-composite').screenshot({path:'qa-priority2/atlas-desktop.png'});
 await page.locator('#nta-relations').scrollIntoViewIfNeeded();
 await page.locator('#nta-scatter svg').waitFor();
 await page.locator('#nta-relations').screenshot({path:'qa-priority2/relations-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(350);
 await page.locator('#nta-composite').scrollIntoViewIfNeeded();
 result.mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 result.overflowElements=await page.evaluate(()=>[...document.querySelectorAll('main *')].filter(e=>e.getBoundingClientRect().right>innerWidth+2&&!e.closest('.table-wrap')).slice(0,15).map(e=>({tag:e.tagName,id:e.id,cls:e.className,width:e.getBoundingClientRect().width,right:e.getBoundingClientRect().right})));
 await page.locator('#nta-composite').screenshot({path:'qa-priority2/atlas-mobile.png'});
 result.errors=errors;result.scope='Local real-browser check; external tiles and weather blocked deliberately.';
 fs.writeFileSync('qa-priority2/result.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result));
 await browser.close();if(errors.length||result.mobileOverflow)process.exitCode=1;
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await browser?.close();server?.kill();});
